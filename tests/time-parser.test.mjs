describe('领域层纯度', () => {
  const FORBIDDEN = [
    ['document', /\bdocument\b/],
    ['window', /\bwindow\b/],
    ['fetch', /\bfetch\s*\(/],
    ['localStorage', /\blocalStorage\b/],
    ['XMLHttpRequest', /\bXMLHttpRequest\b/],
    ['import / require', /\b(?:import|require)\s*[({'"`]/]
  ];

  for (const [name, re] of FORBIDDEN) {
    test(`不出现 ${name}`, () => {
      assert.equal(re.test(source), false);
    });
  }

  test('不自己读当前时间', () => {
    assert.equal(/new\s+Date\s*\(\s*\)/.test(source), false,
      '不得有无参 new Date()');
    assert.equal(/Date\s*\.\s*now\s*\(/.test(source), false,
      '不得有 Date.now()；now 必须由调用方注入');
  });

  test('未注入 now 时抛错，而不是悄悄用系统时间', () => {
    // 领域层跑在 vm 里，它抛出的 TypeError 与本测试文件的 TypeError 不是同一个
    // 构造器，因此不能用 assert.throws(fn, TypeError)（instanceof 跨 realm 会失败）。
    // 改为匹配错误信息。
    assert.throws(() => timeParser('明天'), /需要注入有效的 now/);
    assert.throws(() => timeParser('明天', null), /需要注入有效的 now/);
    assert.throws(() => timeParser('明天', new Date(NaN)), /需要注入有效的 now/);
  });
});
