describe('边界：跨月与跨年', () => {
  test('跨月', () => {
    assert.equal(parse('明天', new Date(2026, 9, 31, 10, 0)), '2026-11-01 23:59');
    assert.equal(parse('3天后', new Date(2026, 9, 31, 10, 0)), '2026-11-03 23:59');
  });

  test('跨年：无年份的月日，已过则顺延下一年', () => {
    const endOfYear = new Date(2026, 11, 30, 10, 0);
    assert.equal(parse('1月5日', endOfYear), '2027-01-05 23:59');
    assert.equal(parse('12月31日', endOfYear), '2026-12-31 23:59');
  });

  test('写了年份则不顺延', () => {
    assert.equal(parse('2026年1月5日', new Date(2026, 11, 30, 10, 0)), '2026-01-05 23:59');
  });
});

describe('边界：闰年', () => {
  test('闰年 2月29日 有效', () => {
    assert.equal(parse('2月29日', new Date(2028, 1, 28, 10, 0)), '2028-02-29 23:59');
  });

  test('平年 2月29日 不存在 → null', () => {
    assert.equal(parse('2月29日', new Date(2027, 1, 28, 10, 0)), null);
  });

  test('2月30日 在任何年份都不存在 → null', () => {
    assert.equal(parse('2月30日', new Date(2028, 1, 28, 10, 0)), null);
  });
});

describe('边界：今天已过的时间点 → 次日', () => {
  test('带时段词：已过则次日同一时刻', () => {
    const evening = new Date(2026, 9, 9, 20, 0);
    assert.equal(parse('下午三点', evening), '2026-10-10 15:00');
    assert.equal(parse('上午十一点', evening), '2026-10-10 11:00');
  });

  test('裸 X点：按 12/24 小时推断，都过了才顺延次日', () => {
    assert.equal(parse('三点', new Date(2026, 9, 9, 9, 0)), '2026-10-09 15:00',
      '上午 9 点时说「三点」指下午三点');
    assert.equal(parse('三点', new Date(2026, 9, 9, 20, 0)), '2026-10-10 03:00',
      '两个候选都过了，顺延次日');
  });

  test('未到的时间点留在今天', () => {
    assert.equal(parse('下午三点', new Date(2026, 9, 9, 10, 0)), '2026-10-09 15:00');
  });
});

describe('边界：周的定义（周一为一周之始，已过则顺延）', () => {
  const sunday = new Date(2026, 9, 11, 10, 0);   // 2026-10-11 周日

  test('周日看本周：已过的顺延下周，当天不推', () => {
    assert.equal(parse('周一', sunday), '2026-10-12 23:59');
    assert.equal(parse('周六', sunday), '2026-10-17 23:59');
    assert.equal(parse('周日', sunday), '2026-10-11 23:59');
  });

  test('周末 = 周六，已过则顺延下周', () => {
    assert.equal(parse('周末', sunday), '2026-10-17 23:59');
    assert.equal(parse('周末', NOW), '2026-10-10 23:59');
  });

  test('下周X 不看是否已过', () => {
    assert.equal(parse('下周一', sunday), '2026-10-12 23:59');
    assert.equal(parse('下周日', sunday), '2026-10-18 23:59');
  });
});

describe('边界：工作日', () => {
  test('跳过周六日', () => {
    // 基准 2026-10-09 周五
    assert.equal(parse('1个工作日', NOW), '2026-10-12 23:59');   // 跨过周六日
    assert.equal(parse('2个工作日', NOW), '2026-10-13 23:59');
    assert.equal(parse('5个工作日', NOW), '2026-10-16 23:59');
  });
});

describe('边界：时间点不成立的情形', () => {
  test('非法时刻 → null', () => {
    assert.equal(parse('25:00'), null);
    assert.equal(parse('10:75'), null);
  });

  test('空文本与无时间表达的文本 → null', () => {
    assert.equal(parse(''), null);
    assert.equal(parse('辛苦了'), null);
    assert.equal(parse('这个方案我看过了'), null);
  });

  test('过去的时间点与日期分开处理', () => {
    // 「昨天」属 §2，返回 null，而不是解析成今天
    assert.equal(parse('昨天下午三点'), null);
  });
});

