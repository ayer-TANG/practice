describe('边界：今天已过的时间点 → 次日', () => {
  test('带时段词：已过则次日同一时刻', () => {
    const evening = new Date(2026, 9, 9, 20, 0);
    assert.equal(parse('下午三点', evening), '2026-10-10 15:00');
    assert.equal(parse('上午十一点', evening), '2026-10-10 11:00');
  });

  test('裸 X点：按 12/24 小时推断，都过了才顺延次日', () => {
    assert.equal(parse('三点', new Date(2026, 9, 9, 9, 0)), '2026-10-09 15:00',
      '上午 9 点时说「三点」指下午三点');
    assert.equal(parse('三点', new Date(2026, 9, 9, 20, 0)), '2026-10-10 03:00',
      '两个候选都过了，顺延次日');
  });

  test('未到的时间点留在今天', () => {
    assert.equal(parse('下午三点', new Date(2026, 9, 9, 10, 0)), '2026-10-09 15:00');
  });
});

describe('边界：周的定义（周一为一周之始，已过则顺延）', () => {
  const sunday = new Date(2026, 9, 11, 10, 0);   // 2026-10-11 周日

  test('周日看本周：已过的顺延下周，当天不推', () => {
    assert.equal(parse('周一', sunday), '2026-10-12 23:59');
    assert.equal(parse('周六', sunday), '2026-10-17 23:59');
    assert.equal(parse('周日', sunday), '2026-10-11 23:59');
  });

  test('周末 = 周六，已过则顺延下周', () => {
    assert.equal(parse('周末', sunday), '2026-10-17 23:59');
    assert.equal(parse('周末', NOW), '2026-10-10 23:59');
  });

  test('下周X 不看是否已过', () => {
    assert.equal(parse('下周一', sunday), '2026-10-12 23:59');
    assert.equal(parse('下周日', sunday), '2026-10-18 23:59');
  });
});

