const { timeParser, timeParserDetail } = domain;

// 2026-10-09 是周五。选周五作基准是有意的：
// 「周X」的顺延规则、周末、本周内/下周内都能在同一天里被压到。
const NOW = new Date(2026, 9, 9, 10, 0, 0);

function fmt(d) {
  if (d === null) return null;
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ` +
         `${p(d.getHours())}:${p(d.getMinutes())}`;
}

function parse(text, now = NOW) {
  return fmt(timeParser(text, now));
}

