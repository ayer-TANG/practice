describe('§3 组合上限 [日期段][时间点段][期限后缀段]', () => {
  const cases = [
    ['明天下午三点前', '2026-10-10 15:00'],
    ['下周三上午十点', '2026-10-14 10:00'],
    ['周五之前', '2026-10-09 23:59'],
    ['今天内', '2026-10-09 23:59']
  ];

  for (const [text, expected] of cases) {
    test(`「${text}」→ ${expected}`, () => {
      assert.equal(parse(text), expected);
    });
  }

  test('一句话多个时间表达：取最靠左的第一个', () => {
    assert.equal(parse('明天早上九点前或者后天都行'), '2026-10-10 09:00');
    assert.equal(parse('周五不行的话就下周一'), '2026-10-09 23:59');
  });

  // Phase 8 用真实语料发现的规格缺口：初稿只允许空白与 `，,、` 作为
  // 「日期段」与「时间点段」之间的填充物，但真实通知里
  // 「10月11日（本周日）下午16：00」这种写法很常见。
  // 括号里写星期几是同位语注释，不是在换话题。规格已同步修订（§0）。
  test('日期与时间点之间隔着一个括号插入语 —— 仍算组合（Phase 8 补）', () => {
    assert.equal(parse('11月18日（周三）下午两点前交'), '2026-11-18 14:00');
    assert.equal(parse('11月18日(周三)下午两点前交'), '2026-11-18 14:00');
    assert.equal(parse('11月18日（周三），下午两点前交'), '2026-11-18 14:00');
  });

  test('括号未闭合 —— 视为换了话题，不组合', () => {
    assert.equal(parse('11月18日（周三下午两点前交'), '2026-11-18 23:59');
  });

  test('括号过长 —— 视为换了话题，不组合', () => {
    assert.equal(
      parse('11月18日（这段插入语故意写得很长很长很长很长很长很长很长）下午两点前交'),
      '2026-11-18 23:59');
  });

  test('没有括号时行为不变 —— 反例仍不组合', () => {
    assert.equal(parse('11月18日再说，2点开会'), '2026-11-18 23:59');
  });

  // Phase 8 第 2 组真实语料暴露的**规格错误**（不是缺口）。
  //
  // §0 的「时间粒度 → 具体时刻」表写着「给了时间点（`明天下午三点`）→ 该时间点」，
  // 但 §0 后半的「取最靠左的第一个」在左端是「日期段自带约定/日终时刻」时把它推翻：
  // `今晚`、`明早` 等被实现成 'absolute'，自带的约定时刻把后面**显式写出**的
  // 时间点整个吞掉。约定时刻是缺省值，不是结论。规格已同步修订（§0）。
  //
  // 三处「碰巧对」掩盖了它：`明天早上九点`（约定 9:00 == 显式九点）、
  // `今晚8点`（约定 20:00 == 显式 8 点）、`下午16:00`。所以下面刻意用
  // **约定时刻与显式时刻不一致**的例子，否则断言不成立。
  test('日期段自带的约定时刻不吞掉显式时间点（Phase 8 补）', () => {
    assert.equal(parse('明天早上8点集合'), '2026-10-10 08:00');
    assert.equal(parse('今晚24点截止'), '2026-10-10 00:00');
    assert.equal(parse('明晚七点开班会'), '2026-10-10 19:00');
    assert.equal(parse('后天下午三点开会'), '2026-10-11 15:00');
    assert.equal(parse('大后天下午三点开会'), '2026-10-12 15:00');
  });

  test('自带时段词的日期段决定裸 X点 的 12/24（Phase 8 补）', () => {
    // 「晚」→ 8 读作 20；「早」→ 8 读作 08。与 §0「带时段词者制式已由时段词确定」一致
    assert.equal(parse('今晚8点开会'), '2026-10-09 20:00');
    assert.equal(parse('明天早上8点集合'), '2026-10-10 08:00');
    // 24 ≥ 13 → 按 24 小时制，不再修正
    assert.equal(parse('今晚24点截止'), '2026-10-10 00:00');
  });

  test('约定时刻只在没有显式时间点时生效（Phase 8 补）', () => {
    assert.equal(parse('今晚'), '2026-10-09 20:00');
    assert.equal(parse('明早'), '2026-10-10 09:00');
    assert.equal(parse('明天早上交作业'), '2026-10-10 09:00');
    assert.equal(parse('后天再说'), '2026-10-11 23:59');
    // 反例：间隔了不能跳过的字，就不算组合 —— 与括号那组同一条规矩
    assert.equal(parse('今晚的会2点开'), '2026-10-09 20:00');
  });

  test('期限后缀段是终段，其后的时间点不参与组合（Phase 8 固化）', () => {
    // §3 的段序是 [日期段][时间点段][期限后缀段]，后缀已在末位。
    // 这一条是 Phase 8 特意固化的现状：不得因为上面的修改而顺手扩大组合范围。
    assert.equal(parse('三天内下午三点交'), '2026-10-12 23:59');
    assert.equal(parse('三个工作日内下午三点交'), '2026-10-14 23:59');
  });
});

