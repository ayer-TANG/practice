describe('边界：跨月与跨年', () => {
  test('跨月', () => {
    assert.equal(parse('明天', new Date(2026, 9, 31, 10, 0)), '2026-11-01 23:59');
    assert.equal(parse('3天后', new Date(2026, 9, 31, 10, 0)), '2026-11-03 23:59');
  });

  // F8-6（Phase 8，用户决策）：**无年份的月日已过也不回卷**。
  // 原规则「该日已过则顺延到下一年」会把通知里的旧日期静默改成明年，
  // 列表上看不出 2026 还是 2027。现在取当年的该日——落在过去就落在过去。
  test('无年份的月日：已过不回卷到明年，取当年该日（视为逾期）', () => {
    const endOfYear = new Date(2026, 11, 30, 10, 0);
    assert.equal(parse('1月5日', endOfYear), '2026-01-05 23:59',
      '已过 —— 仍取 2026 年，不顺延到 2027');
    assert.equal(parse('12月31日', endOfYear), '2026-12-31 23:59', '未过 —— 当年');

    const midOct = new Date(2026, 9, 9, 10, 0);
    assert.equal(parse('3月20日', midOct), '2026-03-20 23:59',
      '10 月回看 3 月：逾期，不是 2027-03-20');
    assert.equal(parse('3/20', midOct), '2026-03-20 23:59', 'X/X 同规则');
    assert.equal(parse('3-20', midOct), '2026-03-20 23:59', 'X-Y 同规则');
    assert.equal(parse('10月20日', midOct), '2026-10-20 23:59', '未过 —— 当年');
  });

  test('写了年份则不受回卷规则影响（本就写死）', () => {
    assert.equal(parse('2026年1月5日', new Date(2026, 11, 30, 10, 0)), '2026-01-05 23:59');
    assert.equal(parse('2027年1月5日', new Date(2026, 11, 30, 10, 0)), '2027-01-05 23:59');
  });

  // F8-10：带年份的**数字**日期（`YYYY-MM-DD` / `YYYY/M/D`）。
  // 修之前这种写法整段落空，`03-20` 掉进无年份的 `X-Y`，于是「写明了年份反而被
  // 忽略」，在 `now` 已过该日时顺延到下一年 —— 静默的错值。
  test('带年份的数字日期：即便已过也不回卷到下一年', () => {
    const now = new Date(2026, 9, 9, 10, 0);          // 2026-10-09
    assert.equal(parse('2026-03-20', now), '2026-03-20 23:59');
    assert.equal(parse('2026/3/5', now), '2026-03-05 23:59');
    assert.equal(parse('2026-03-20 23:59', now), '2026-03-20 23:59',
      '后面跟显式时刻段时走 §3 组合');
  });

  test('带年份的数字日期：非法值仍是 null，不误吞其他数字', () => {
    const now = new Date(2026, 9, 9, 10, 0);
    assert.equal(parse('2026-13-40', now), null, '月份越界');
    assert.equal(parse('2026-02-30', now), null, '该月没有这一天');
    assert.equal(parse('2025-2026学年', now), null, '学年区间不是日期');
    assert.equal(parse('2026-02-29', now), null, '2026 不是闰年');
  });
});

